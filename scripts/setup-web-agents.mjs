// Creates or updates the locked ElevenLabs agents for Bit and Byte, then writes
// their ids to functions/web-agent-ids.js. This account also holds other
// clients' agents, so it only updates agents and tools it recorded there.
//
// ELEVENLABS_API_KEY="$(firebase functions:secrets:access ELEVENLABS_API_KEY --project bitesites-org)" node scripts/setup-web-agents.mjs
import {writeFileSync} from 'node:fs';
import {WEB_AGENT_IDS} from '../functions/web-agent-ids.js';
import {bitAgentConfig,bitToolConfigs,byteAgentConfig,byteToolConfigs} from '../functions/web-agents.js';

const key=process.env.ELEVENLABS_API_KEY;
if(!key)throw new Error('ELEVENLABS_API_KEY is required.');
const api=async(path,options={})=>{
 const response=await fetch(`https://api.elevenlabs.io${path}`,{...options,headers:{'xi-api-key':key,'Content-Type':'application/json'}});
 const text=await response.text();
 if(!response.ok)throw new Error(`${options.method||'GET'} ${path} -> ${response.status}: ${text.slice(0,700)}`);
 return text?JSON.parse(text):{};
};

const syncTools=async(configs,known={})=>{
 const ids={};
 for(const config of configs){
  const {name}=config.tool_config;
  if(known[name]){await api(`/v1/convai/tools/${known[name]}`,{method:'PATCH',body:JSON.stringify(config)});ids[name]=known[name];}
  else ids[name]=(await api('/v1/convai/tools',{method:'POST',body:JSON.stringify(config)})).id;
 }
 return ids;
};
const syncAgent=async(config,known)=>{
 if(known){await api(`/v1/convai/agents/${known}`,{method:'PATCH',body:JSON.stringify(config)});return known;}
 return (await api('/v1/convai/agents/create',{method:'POST',body:JSON.stringify(config)})).agent_id;
};

const bitTools=await syncTools(bitToolConfigs(),WEB_AGENT_IDS.bitTools);
const byteTools=await syncTools(byteToolConfigs(),WEB_AGENT_IDS.byteTools);
const ids={
 bit:await syncAgent(bitAgentConfig({toolIds:Object.values(bitTools)}),WEB_AGENT_IDS.bit),
 byte:await syncAgent(byteAgentConfig({toolIds:Object.values(byteTools)}),WEB_AGENT_IDS.byte),
 bitTools,byteTools
};
writeFileSync(new URL('../functions/web-agent-ids.js',import.meta.url),`// Generated by scripts/setup-web-agents.mjs. Do not edit by hand.\nexport const WEB_AGENT_IDS = Object.freeze(${JSON.stringify(ids,null,2)});\n`);
console.log(`Bit ${ids.bit} with ${Object.keys(bitTools).length} tools; Byte ${ids.byte} with ${Object.keys(byteTools).length} tools`);
