// Creates or updates one locked ElevenLabs agent per practice scenario, then
// writes their ids to functions/rep-practice-agents.js. Rerun after any change
// to a scenario, prompt or scoring rule. Only agents named "BiteSites Practice"
// are touched, because this ElevenLabs account also holds other clients' agents.
//
// ELEVENLABS_API_KEY="$(firebase functions:secrets:access ELEVENLABS_API_KEY --project bitesites-org)" node scripts/setup-practice-agents.mjs
import {writeFileSync} from 'node:fs';
import {getAccount} from '../functions/accounts.js';
import {allRepTrainingScenarios,practiceAgentConfig} from '../functions/rep-training.js';

const key=process.env.ELEVENLABS_API_KEY;
if(!key)throw new Error('ELEVENLABS_API_KEY is required.');
const api=async(path,options={})=>{
 const response=await fetch(`https://api.elevenlabs.io${path}`,{...options,headers:{'xi-api-key':key,'Content-Type':'application/json'}});
 const text=await response.text();
 if(!response.ok)throw new Error(`${options.method||'GET'} ${path.split('?')[0]} -> ${response.status}: ${text.slice(0,600)}`);
 return text?JSON.parse(text):{};
};

const existing=new Map();
const {agents=[]}=await api('/v1/convai/agents?page_size=100&search=BiteSites%20Practice');
for(const agent of agents)if(agent.name?.startsWith('BiteSites Practice - '))existing.set(agent.name,agent.agent_id);

const ids={};
for(const {accountId,scenario} of allRepTrainingScenarios()){
 const config=practiceAgentConfig({sellerName:getAccount(accountId)?.label||accountId,scenario});
 const current=existing.get(config.name);
 if(current){
  await api(`/v1/convai/agents/${current}`,{method:'PATCH',body:JSON.stringify(config)});
  ids[scenario.id]=current;
  console.log(`updated ${config.name}`);
 }else{
  const created=await api('/v1/convai/agents/create',{method:'POST',body:JSON.stringify(config)});
  ids[scenario.id]=created.agent_id;
  console.log(`created ${config.name}`);
 }
}
const lines=Object.entries(ids).map(([id,agentId])=>`  '${id}': '${agentId}'`).join(',\n');
writeFileSync(new URL('../functions/rep-practice-agents.js',import.meta.url),`// Generated by scripts/setup-practice-agents.mjs. Do not edit by hand.\nexport const PRACTICE_AGENT_IDS = Object.freeze({\n${lines}\n});\n`);
console.log(`${Object.keys(ids).length} agents ready`);
